def adaptive_eyre_milton_thermoporoelasticity(
    L_φ, biot, κ, μ, ν, p_macro, alpha, dhyd_ite_mask, T_macro,
    ε_macro, e, green_op_name="willot2015", mu0=None, **kwargs,
):
    """
    Adaptive Eyre-Milton scheme & more

    """
    # user
    print('initialization of the FFT solver')

    # ----- Problem dimension -----
    
    φ_dim = L_φ[0].ndim
    φ_shape = L_φ[0].shape

    # ----- Reference material -----

    ν0 = ν[1]  # reference material is set to rock matrix
    μ0 = μ[1]
    if mu0 is not None:
        μ0 = mu0
    C0 = material.create(μ0, ν0, φ_dim)

    # ----- Sollicitation -----
    
    p0 = p_macro[0] 
    t0 = T_macro[0]

    # ----- ??? -----
    
    a_κ = np.zeros_like(L_φ[0])
    a_μ = np.zeros_like(L_φ[0])

    # plan the next work
    if len(L_φ) > 2:
        raise ValueError('Check the interpolation of the parameters')

    # iterate on the minerals
    for i_φ in range(1, len(L_φ)):
        phi_0 = 1-L_φ[i_φ]
        phi_i = L_φ[i_φ]
        a_κ = a_κ + κ[0] * phi_0 + κ[i_φ] * phi_i
        a_μ = a_μ + μ[0] * phi_0 + μ[i_φ] * phi_i

    # compute the alpha tensor               
    α = alpha_tensor(C0, a_κ, a_μ, φ_dim, φ_shape)
    
    # create a material S0
    S0 = material.create(
         1 / (C0.g * 4),
         material.poisson_from_bulk_and_shear_moduli(
             1 / (C0.k * φ_dim**2), 1 / (C0.g * 4), φ_dim
         ),
         φ_dim,
    )
    
    # compute the green operator
    Γ0 = green_operator(C0, φ_shape, green_op_name=kwargs.get("green_operator", green_op_name))
    
    # compute ??
    κ_D = 2 * a_κ * C0.k / (a_κ + C0.k)
    μ_D = 2 * a_μ * C0.g / (a_μ + C0.g)
    κ_D[a_μ == np.inf] = 2 * C0.k
    μ_D[a_μ == np.inf] = 2 * C0.g
    κ_S = 2 * C0.k**2 / (a_κ + C0.k)
    μ_S = 2 * C0.g**2 / (a_μ + C0.g)
    κ_S[a_μ == np.inf] = 0
    μ_S[a_μ == np.inf] = 0

    # compute the operator
    B = operatorB(φ_dim, φ_shape, L_φ, biot)
    B2 = operatorB2(φ_dim, φ_shape, L_φ, biot)
    A = operatorA(φ_dim, φ_shape, L_φ, alpha, dhyd_ite_mask)
    A2 = operatorA2(φ_dim, φ_shape, L_φ, alpha, dhyd_ite_mask)
    
    C_D = local_operator(φ_dim, φ_shape, φ_dim * κ_D, 2 * μ_D)
    C_SD = local_operator(φ_dim, φ_shape, φ_dim * (κ_D - κ_S), 2 * (μ_D - μ_S))
    ΔC = local_operator(φ_dim, φ_shape, φ_dim * (a_κ - C0.k), 2 * (a_μ - C0.g))

    def ref_norm(X):
        X_ = as_grid(X)
        return np.sqrt(np.sum(X_ * C_ε(C0, X_)))

    as_grid = lambda a: np.reshape(a, Γ0.oshape)
    as_vector = lambda a: a.ravel()


    def projections_on_D_S(X):
        XD = Γ0 @ C_ε(C0, as_grid(X)).ravel()
        return XD, X - XD

    def projection_on_D(X):
        return Γ0 @ C_ε(C0, as_grid(X)).ravel()

    # ----- Fields Initialization -----
    C = local_operator(φ_dim, φ_shape, φ_dim * a_κ, 2 * a_μ)
    E_macro = np.zeros(Γ0.oshape)
    E_macro[...] = ε_macro
    E_norm = ref_norm(E_macro)
    E_macro = as_vector(E_macro)
    ε = np.zeros_like(E_macro)
    σ = np.zeros_like(E_macro)

    k = C @ A
    X = E_macro - Γ0 @ (- p0 * B - k * t0)


    λ = 0.0
    if kwargs.get("lambda_value", False):  # a given fixed value of lambda
        λ = kwargs.get("lambda_value", False)
    ε_old = np.zeros_like(ε)

    i = 0
    first_iteration = True
    while True:

        if (i) % 10 == 0:
            print(f"Adaptive Eyre–Milton, iteration #{i + 1}", flush=True)

        XD, XS = projections_on_D_S(X)

        Z = α @ X + Γ0 @ C_SD @ X 
        X_, Z_ = as_grid(X), as_grid(Z)
        λ = np.sum(X_ * C_ε(C0, Z_)) / np.sum(Z_ * C_ε(C0, Z_))

        if kwargs.get("lambda_value", False):  # a given fixed value of lambda
            λ = kwargs.get("lambda_value", False)

        ε = E_macro - Γ0 @ (ΔC @ ε - p0 * B - k * t0) + λ * α @ X
        stress_polarization = ΔC @ ε
        σ = C @ ε - (p0 * B) - (k * t0) + λ * C_D @ X 
        Delta_D = ref_norm(XS) / ref_norm(C_ε(S0, as_grid(σ)))
        
        X -= λ * Z

        if not first_iteration and (i) % 10 == 0:
            print('(residual)', round(Delta_D,4),' /', e, '(tolerance)')
            if not first_iteration and Delta_D < e:
                print(f"Converged at iteration {i + 1}")
                break

        first_iteration = False
        i += 1
        
    return as_grid(σ), as_grid(ε), as_grid(stress_polarization)


