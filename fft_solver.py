def operatorA2(φ_dim, φ_shape, L_φ, alpha, dhyd_ite_mask):
    '''
    Compute the operator A2.
    '''
    blocks = []
    if φ_dim == 3:
        for i in range(φ_shape[0]):
            for j in range(φ_shape[1]):
                for l in range(φ_shape[2]):
                    a_ = 0
                    for i_φ in range(len(L_φ)):
                        a_ = a_+ L_φ[i_φ][i, j, l]*alpha[i_φ]*dhyd_ite_mask[i, j, l]
                    alpha_ = np.array([a_, a_, 0, 0, 0, 0])
                    block = alpha_.reshape(1, 6)
                    blocks.append(block)

    alpha_t = block_diag(blocks)

    return aslinearoperator(alpha_t)

