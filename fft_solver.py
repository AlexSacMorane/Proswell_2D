def alpha_tensor(C0, κ, μ, φ_dim, φ_shape):
    '''
    Compute the tensor alpha
    '''
    ak = 2 * C0.k / (κ + C0.k)
    ak[μ == np.inf] = 0
    ag = 2 * C0.g / (μ + C0.g)
    ag[μ == np.inf] = 0
    α = local_operator(φ_dim, φ_shape, ak, ag)
    return α

