def first_lame_coefficient(μ, ν):
    '''
    Compute the lame coefficients from the poisson ratio and the shear modulus.
    '''
    return 2.0 * μ * ν / (1.0 - 2.0 * ν)

#-------------------------------------------------------------------------------

def C_ε(C, ε):
    '''
    Compute the stress tensor, considering linear elasticity and isotropy.
    '''
    ε = np.asarray(ε)
    d = C.dim
    μ = C.g
    λ = first_lame_coefficient(C.g, C.nu)
    tr_ε = np.sum(ε[..., :d], axis=-1, keepdims=1)
    σ = 2 * μ * ε
    σ[..., :d] += λ * tr_ε
    return σ

