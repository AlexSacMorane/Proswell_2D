def green_operator(C, grid_shape, green_op_name):
    '''
    Return the green operator.
    '''
    if green_op_name == "truncated":
        print("Using Green truncated operator")
        op = green.truncated(
            C.green_operator(), grid_shape, 1.0, fft.create_real(grid_shape)
        )
    elif green_op_name == "filtered":
        print("Using Green filtered operator")
        op = green.filtered(
            C.green_operator(), grid_shape, 1.0, fft.create_real(grid_shape)
        )
    elif green_op_name == "willot2015":
        print("Using Green 'willot 2015' operator")
        op = green.willot2015(
            C.green_operator(), grid_shape, 1.0, fft.create_real(grid_shape)
        )
    return MyLinearOperator(op)

